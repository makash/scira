fn detect_llm_config() -> Result<Option<LlmConfig>> {
    let explicit_provider = env::var("SCIRA_LLM_PROVIDER").ok();
    let explicit_model = env::var("SCIRA_LLM_MODEL").ok();
    let explicit_base_url = env::var("SCIRA_LLM_BASE_URL").ok();
    let scira_key = env::var("SCIRA_LLM_API_KEY").ok();

    let provider_and_key = if let Some(provider) = explicit_provider {
        let provider = parse_provider(&provider)?;
        let key = scira_key
            .or_else(|| provider_native_key(provider))
            .ok_or_else(|| {
                anyhow!("SCIRA_LLM_PROVIDER is set but no matching API key was found")
            })?;
        Some((provider, key))
    } else if let Some(key) = env::var("ANTHROPIC_API_KEY").ok() {
        Some((LlmProvider::Anthropic, key))
    } else if let Some(key) = env::var("OPENAI_API_KEY").ok() {
        Some((LlmProvider::Openai, key))
    } else if let Some(key) = env::var("GEMINI_API_KEY")
        .ok()
        .or_else(|| env::var("GOOGLE_API_KEY").ok())
    {
        Some((LlmProvider::Gemini, key))
    } else if let Some(key) = scira_key {
        Some((infer_provider_from_key(&key)?, key))
    } else {
        None
    };

    let Some((provider, api_key)) = provider_and_key else {
        return Ok(None);
    };

    let model = explicit_model.unwrap_or_else(|| default_model(provider).to_string());

    Ok(Some(LlmConfig {
        provider,
        api_key,
        model,
        base_url: explicit_base_url,
    }))
}

fn parse_provider(value: &str) -> Result<LlmProvider> {
    match value.trim().to_lowercase().as_str() {
        "anthropic" => Ok(LlmProvider::Anthropic),
        "openai" | "chatgpt" => Ok(LlmProvider::Openai),
        "gemini" | "google" => Ok(LlmProvider::Gemini),
        other => Err(anyhow!(
            "unsupported provider `{other}`; use anthropic, openai, or gemini"
        )),
    }
}

fn provider_native_key(provider: LlmProvider) -> Option<String> {
    match provider {
        LlmProvider::Anthropic => env::var("ANTHROPIC_API_KEY").ok(),
        LlmProvider::Openai => env::var("OPENAI_API_KEY").ok(),
        LlmProvider::Gemini => env::var("GEMINI_API_KEY")
            .ok()
            .or_else(|| env::var("GOOGLE_API_KEY").ok()),
    }
}

fn infer_provider_from_key(key: &str) -> Result<LlmProvider> {
    if key.starts_with("sk-ant-") {
        Ok(LlmProvider::Anthropic)
    } else if key.starts_with("AIza") {
        Ok(LlmProvider::Gemini)
    } else if key.starts_with("sk-") || key.starts_with("sk-proj-") {
        Ok(LlmProvider::Openai)
    } else {
        Err(anyhow!(
            "SCIRA_LLM_API_KEY was found, but scira could not infer the provider from the key shape. Set SCIRA_LLM_PROVIDER explicitly."
        ))
    }
}

fn default_model(provider: LlmProvider) -> &'static str {
    match provider {
        LlmProvider::Anthropic => "claude-3-5-sonnet-latest",
        LlmProvider::Openai => "gpt-4.1",
        LlmProvider::Gemini => "gemini-2.5-pro",
    }
}

