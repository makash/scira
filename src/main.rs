fn exit_code_for_status(status: IncidentStatus) -> i32 {
    match status {
        IncidentStatus::NoIndicatorsFound => 0,
        IncidentStatus::ReferencesFoundFollowUpNeeded => 10,
        IncidentStatus::LikelyAffected => 20,
    }
}

