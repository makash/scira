fn collect_npm_dependency_findings(
    profile: &IncidentProfile,
    target: &Path,
    package: &str,
    check: &str,
    global: bool,
    result: &mut PythonEnvScan,
) {
    let args = if global {
        vec!["ls", "-g", "--depth=0", package, "--json"]
    } else {
        vec!["ls", package, "--all", "--json"]
    };

    match run_command_capture_in_dir("npm", &args, if global { None } else { Some(target) }) {
        Ok(output) if output.status.success() || !output.stdout.trim().is_empty() => {
            let matches = parse_npm_ls_versions(&output.stdout, package, profile.bad_versions);
            if matches.is_empty() {
                result.findings.push(EnvironmentFinding {
                    check: check.to_string(),
                    status: "not_present".to_string(),
                    details: format!("Package {package} not found via npm ls"),
                    version: None,
                    bad_version: false,
                    raw: None,
                });
            } else {
                for npm_match in matches {
                    result.findings.push(EnvironmentFinding {
                        check: check.to_string(),
                        status: "present".to_string(),
                        details: if global {
                            format!(
                                "Global npm package {package} found{}",
                                npm_match
                                    .path_hint
                                    .as_deref()
                                    .map(|p| format!(" via {p}"))
                                    .unwrap_or_default()
                            )
                        } else {
                            format!(
                                "npm dependency {package} found{}",
                                npm_match
                                    .path_hint
                                    .as_deref()
                                    .map(|p| format!(" via {p}"))
                                    .unwrap_or_default()
                            )
                        },
                        bad_version: npm_match.bad_version,
                        version: Some(npm_match.version),
                        raw: None,
                    });
                }
            }
        }
        Ok(output) => {
            result.findings.push(EnvironmentFinding {
                check: check.to_string(),
                status: "not_present".to_string(),
                details: format!("Package {package} not found via npm ls"),
                version: None,
                bad_version: false,
                raw: if output.stderr.trim().is_empty() {
                    None
                } else {
                    Some(output.stderr)
                },
            });
        }
        Err(err) => result.skipped_checks.push(SkippedCheck {
            check: check.to_string(),
            reason: err.to_string(),
        }),
    }
}

#[derive(Debug)]
struct NpmMatch {
    version: String,
    bad_version: bool,
    path_hint: Option<String>,
}

fn parse_npm_ls_versions(output: &str, package: &str, bad_versions: &[&str]) -> Vec<NpmMatch> {
    let Ok(json) = serde_json::from_str::<Value>(output) else {
        return Vec::new();
    };
    let mut matches = Vec::new();
    collect_npm_matches_from_value(&json, package, bad_versions, &mut Vec::new(), &mut matches);
    matches
}

fn collect_npm_matches_from_value(
    value: &Value,
    package: &str,
    bad_versions: &[&str],
    stack: &mut Vec<String>,
    matches: &mut Vec<NpmMatch>,
) {
    if let Some(name) = value.get("name").and_then(|v| v.as_str()) {
        if !name.is_empty() {
            stack.push(name.to_string());
        }
    }

    let current_name = value.get("name").and_then(|v| v.as_str());
    let current_version = value.get("version").and_then(|v| v.as_str());
    if current_name == Some(package) {
        if let Some(version) = current_version {
            matches.push(NpmMatch {
                version: version.to_string(),
                bad_version: bad_versions.iter().any(|bad| *bad == version),
                path_hint: if stack.is_empty() {
                    None
                } else {
                    Some(stack.join(" > "))
                },
            });
        }
    }

    if let Some(dependencies) = value.get("dependencies").and_then(|v| v.as_object()) {
        for (dep_name, dep_value) in dependencies {
            if dep_name == package {
                let version = dep_value
                    .get("version")
                    .and_then(|v| v.as_str())
                    .unwrap_or("unknown");
                let mut path_stack = stack.clone();
                path_stack.push(dep_name.clone());
                matches.push(NpmMatch {
                    version: version.to_string(),
                    bad_version: bad_versions.iter().any(|bad| *bad == version),
                    path_hint: Some(path_stack.join(" > ")),
                });
            }
            collect_npm_matches_from_value(dep_value, package, bad_versions, stack, matches);
        }
    }

    if current_name.is_some() {
        let _ = stack.pop();
    }
}

fn detect_python() -> Option<String> {
    if command_exists("python") {
        Some("python".to_string())
    } else if command_exists("python3") {
        Some("python3".to_string())
    } else {
        None
    }
}

fn command_exists(command: &str) -> bool {
    Command::new(command)
        .arg("--version")
        .output()
        .map(|_| true)
        .unwrap_or(false)
}

fn run_command_capture(command: &str, args: &[&str]) -> io::Result<CommandOutput> {
    run_command_capture_in_dir(command, args, None)
}

fn run_command_capture_in_dir(
    command: &str,
    args: &[&str],
    dir: Option<&Path>,
) -> io::Result<CommandOutput> {
    let mut cmd = Command::new(command);
    cmd.args(args);
    if let Some(dir) = dir {
        cmd.current_dir(dir);
    }
    let output = cmd.output()?;
    Ok(CommandOutput {
        status: output.status,
        stdout: String::from_utf8_lossy(&output.stdout).to_string(),
        stderr: String::from_utf8_lossy(&output.stderr).to_string(),
    })
}

struct CommandOutput {
    status: std::process::ExitStatus,
    stdout: String,
    stderr: String,
}

fn parse_pip_show_field(output: &str, field: &str) -> Option<String> {
    output.lines().find_map(|line| {
        line.strip_prefix(&format!("{field}:"))
            .map(|value| value.trim().to_string())
    })
}

fn detect_hostname() -> String {
    env::var("HOSTNAME")
        .or_else(|_| env::var("COMPUTERNAME"))
        .or_else(|_| {
            run_command_capture("hostname", &[])
                .map(|out| out.stdout.trim().to_string())
                .map_err(|_| env::VarError::NotPresent)
        })
        .unwrap_or_else(|_| "unknown-host".to_string())
}

fn detect_user() -> String {
    env::var("USER")
        .or_else(|_| env::var("USERNAME"))
        .unwrap_or_else(|_| "unknown-user".to_string())
}

fn home_dir() -> Option<PathBuf> {
    env::var_os("HOME").map(PathBuf::from)
}

fn build_matcher(patterns: &[&str]) -> Result<GlobSet> {
    let mut builder = GlobSetBuilder::new();
    for pattern in patterns {
        builder
            .add(Glob::new(pattern).with_context(|| format!("invalid glob pattern: {pattern}"))?);
    }
    Ok(builder.build()?)
}

fn classify_version(profile: &IncidentProfile, version: &str) -> VersionHitStatus {
    if profile.bad_versions.iter().any(|bad| bad == &version) {
        VersionHitStatus::Compromised
    } else if profile
        .safe_version
        .split('/')
        .map(|v| v.trim())
        .any(|safe| safe == version)
    {
        VersionHitStatus::Safe
    } else {
        VersionHitStatus::Other
    }
}

fn is_exact_npm_version(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('^')
        && !value.starts_with('~')
        && !value.starts_with('>')
        && !value.starts_with('<')
        && !value.starts_with('*')
        && !value.contains(" ")
        && !value.contains("||")
        && !value.contains(':')
        && !value.starts_with("workspace:")
        && !value.starts_with("file:")
        && !value.starts_with("git+")
        && value.chars().any(|c| c.is_ascii_digit())
}

fn push_limited(items: &mut Vec<String>, value: String) {
    if items.len() >= MAX_RECORDED_LIMITATION_ITEMS || items.contains(&value) {
        return;
    }
    items.push(value);
}

fn dedupe_paths(paths: &[PathBuf]) -> Vec<PathBuf> {
    let mut seen = BTreeSet::new();
    let mut deduped = Vec::new();
    for path in paths {
        let display = path.display().to_string();
        if seen.insert(display) {
            deduped.push(path.clone());
        }
    }
    deduped
}

fn classify_cache_source(path: &Path) -> String {
    let display = path.display().to_string();
    if display.contains(".cache/pip") {
        "pip_cache".to_string()
    } else if display.contains(".cache/uv") {
        "uv_cache".to_string()
    } else {
        "user_path".to_string()
    }
}

fn should_skip_scan_entry(entry: &DirEntry) -> bool {
    if !entry.file_type().is_dir() {
        return false;
    }

    matches!(
        entry.file_name().to_string_lossy().as_ref(),
        ".git" | "target" | "bundled"
    )
}

fn key_evidence_lines(report: &ScanReport, verbose: bool) -> Vec<String> {
    let mut lines = Vec::new();

    for hit in report
        .findings
        .mcp_risk_hits
        .iter()
        .take(if verbose { 10 } else { 5 })
    {
        lines.push(format!(
            "MCP {} risk `{}` for server `{}` in {}: {}",
            hit.severity.as_str(),
            hit.category,
            hit.server_name,
            hit.source_path,
            hit.evidence
        ));
    }

    for hit in report
        .findings
        .version_hits
        .iter()
        .filter(|hit| matches!(hit.status, VersionHitStatus::Compromised))
        .take(5)
    {
        if hit.line_number > 0 {
            lines.push(format!(
                "Found compromised version {} in {}:{}",
                hit.version, hit.path, hit.line_number
            ));
        } else {
            lines.push(format!(
                "Found compromised version {} in {} ({})",
                hit.version, hit.path, hit.line
            ));
        }
    }

    for finding in report
        .findings
        .environment_hits
        .iter()
        .filter(|f| f.bad_version)
        .take(5)
    {
        if let Some(version) = &finding.version {
            lines.push(format!(
                "Environment check `{}` found compromised version {}",
                finding.check, version
            ));
        }
    }

    for hit in report.findings.ioc_file_hits.iter().take(5) {
        lines.push(format!("Found IOC file {} at {}", hit.indicator, hit.path));
    }

    for hit in report.findings.ioc_domain_hits.iter().take(5) {
        lines.push(format!(
            "Found IOC domain {} in {}:{}",
            hit.indicator,
            hit.path,
            hit.line_number.unwrap_or(0)
        ));
    }

    if lines.is_empty() && !report.findings.manifest_hits.is_empty() {
        for hit in report
            .findings
            .manifest_hits
            .iter()
            .take(if verbose { 10 } else { 5 })
        {
            lines.push(format!(
                "Found package reference in {}:{}",
                hit.path, hit.line_number
            ));
        }
    }

    lines
}

